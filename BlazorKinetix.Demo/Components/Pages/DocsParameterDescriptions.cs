    internal static string GetSpanish(string name)
    {
        if (Spanish.TryGetValue(name, out var description)) return description;
        if (name.EndsWith("Changed", StringComparison.Ordinal))
            return $"Se ejecuta cuando cambia {name[..^7]}.";
        if (name.StartsWith("On", StringComparison.Ordinal))
            return $"Se ejecuta al producirse la acción {name[2..]}.";
        if (name.EndsWith("IconClass", StringComparison.Ordinal))
            return "Clase CSS del icono correspondiente.";
        if (name.EndsWith("Icon", StringComparison.Ordinal))
            return "Contenido Razor del icono correspondiente.";
        if (name.EndsWith("Text", StringComparison.Ordinal))
            return "Texto configurable de esta parte del control.";
        return "Configura esta propiedad del control.";
    }
